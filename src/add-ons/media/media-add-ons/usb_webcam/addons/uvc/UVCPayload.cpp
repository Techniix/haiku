/*!	Walks the marker segments up to the start of scan. Returns the offset
	of the SOS marker (or 0 if there is none), and whether a DHT segment
	came before it.
*/
static size_t
find_scan(const uint8* frame, size_t size, bool& hasTables)
{
	hasTables = false;
	if (size < 4 || frame[0] != 0xff || frame[1] != 0xd8)
		return 0;
	size_t offset = 2;
	while (offset + 4 <= size) {
		if (frame[offset] != 0xff)
			return 0;
		uint8 marker = frame[offset + 1];
		if (marker == 0xff) {
			// fill byte
			offset++;
			continue;
		}
		if (marker == 0xda)
			return offset;
		if (marker == 0xc4)
			hasTables = true;
		size_t length = frame[offset + 2] << 8 | frame[offset + 3];
		if (length < 2)
			return 0;
		offset += 2 + length;
	}
	return 0;
}


bool
uvc_mjpeg_has_huffman_tables(const uint8* frame, size_t size)
{
	bool hasTables;
	return find_scan(frame, size, hasTables) != 0 && hasTables;
}


bool
uvc_mjpeg_add_huffman_tables(const uint8* frame, size_t size,
	std::vector<uint8>& jpeg)
{
	bool hasTables;
	size_t scan = find_scan(frame, size, hasTables);
	if (scan == 0)
		return false;
	jpeg.clear();
	if (hasTables) {
		jpeg.assign(frame, frame + size);
		return true;
	}
	jpeg.reserve(size + sizeof(kStandardHuffmanTables));
	jpeg.insert(jpeg.end(), frame, frame + scan);
	jpeg.insert(jpeg.end(), kStandardHuffmanTables,
		kStandardHuffmanTables + sizeof(kStandardHuffmanTables));
	jpeg.insert(jpeg.end(), frame + scan, frame + size);
	return true;
}
