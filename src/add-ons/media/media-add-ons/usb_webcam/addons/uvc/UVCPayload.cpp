#include "UVCPayload.h"

#include <string.h>


enum {
	kHeaderFID = 0x01,
	kHeaderEOF = 0x02,
	kHeaderPTS = 0x04,
	kHeaderSCR = 0x08,
	kHeaderERR = 0x40
};


UVCPayloadParser::UVCPayloadParser(size_t maxFrameSize)
	:
	frames(0),
	droppedErrors(0),
	droppedSize(0),
	invalidHeaders(0),
	outOfSync(0),
	fMaxFrameSize(maxFrameSize),
	fFrameSize(0),
	fActive(false),
	fError(false),
	fFID(-1),
	fLastFID(-1),
	fPTS(0),
	fDonePTS(0)
{
}


void
UVCPayloadParser::Reset()
{
	fCurrent.clear();
	fActive = false;
	fError = false;
	fFID = -1;
	fLastFID = -1;
}


bool
UVCPayloadParser::_Finish()
{
	bool good = true;
	if (fError) {
		droppedErrors++;
		good = false;
	} else if ((fFrameSize != 0 && fCurrent.size() != fFrameSize)
		|| fCurrent.empty()) {
		droppedSize++;
		good = false;
	}
	if (good) {
		fDone.swap(fCurrent);
		fDonePTS = fPTS;
		frames++;
	}
	fCurrent.clear();
	fActive = false;
	fError = false;
	fLastFID = fFID;
	return good;
}


bool
UVCPayloadParser::Write(const uint8* payload, size_t size)
{
	if (size < 2 || payload[0] < 2 || payload[0] > size) {
		invalidHeaders++;
		return false;
	}
	uint8 headerLength = payload[0];
	uint8 flags = payload[1];
	int fid = flags & kHeaderFID;
	bool finished = false;

	// The FID toggled: the frame before ended (without EOF).
	if (fActive && fid != fFID)
		finished = _Finish();

	if (!fActive) {
		if (fid == fLastFID) {
			// the rest of a frame that already ended, or that we joined in
			// the middle: wait for the next one
			outOfSync++;
			return finished;
		}
		fActive = true;
		fFID = fid;
		fCurrent.clear();
		fError = false;
		fPTS = 0;
	}

	if ((flags & kHeaderERR) != 0)
		fError = true;
	if ((flags & kHeaderPTS) != 0 && headerLength >= 6)
		memcpy(&fPTS, payload + 2, 4);

	size_t length = size - headerLength;
	if (fCurrent.size() + length > fMaxFrameSize) {
		fError = true;
		length = fMaxFrameSize > fCurrent.size()
			? fMaxFrameSize - fCurrent.size() : 0;
	}
	fCurrent.insert(fCurrent.end(), payload + headerLength,
		payload + headerLength + length);

	if ((flags & kHeaderEOF) != 0) {
		if (finished) {
			// two frames ended with this payload; keep the newer one
		}
		finished = _Finish() || finished;
	}
	return finished;
}


static inline uint8
clamp(int value)
{
	return value < 0 ? 0 : value > 255 ? 255 : value;
}


void
uvc_yuy2_to_rgb32(const uint8* source, uint8* destination, uint32 width,
	uint32 height, uint32 bytesPerRow)
{
	for (uint32 y = 0; y < height; y++) {
		const uint8* in = source + (size_t)y * width * 2;
		uint8* out = destination + (size_t)y * bytesPerRow;
		for (uint32 x = 0; x + 1 < width + 1; x += 2) {
			int u = in[1] - 128;
			int v = in[3] - 128;
			for (int i = 0; i < 2 && x + i < width; i++) {
				int c = 298 * (in[i * 2] - 16);
				out[0] = clamp((c + 516 * u + 128) >> 8);
				out[1] = clamp((c - 100 * u - 208 * v + 128) >> 8);
				out[2] = clamp((c + 409 * v + 128) >> 8);
				out[3] = 255;
				out += 4;
			}
			in += 4;
		}
	}
}


